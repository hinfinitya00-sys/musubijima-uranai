// ガイド数からガイドを取得する関数
export function getGuideByNumber(guideNumber: number): Guide | undefined {
  return GUIDES.find((g) => g.number === guideNumber);
}

// 生年月日からガイド数を計算する関数
export function calculateGuideNumber(year: number, month: number, day: number): number {
  const digits = `${year}${month}${day}`.split("").map(Number);
  const sum = digits.reduce((acc, d) => acc + d, 0);
  return sum;
}

